-- REVIEW BEFORE APPLYING:
-- Depends on current_user_is_admin() from
-- 20261102_admin_dashboard_read_policies.sql. Verify live orders.id and
-- orders.user_id exist as expected. This migration is not applied remotely.

BEGIN;

CREATE TABLE IF NOT EXISTS public.customer_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (
    event_type IN (
      'product_view',
      'add_to_cart',
      'search',
      'checkout_completed'
    )
  ),
  product_id text,
  search_term text,
  results_count integer,
  order_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT customer_events_payload_valid CHECK (
    (event_type IN ('product_view', 'add_to_cart')
      AND product_id IS NOT NULL
      AND search_term IS NULL
      AND results_count IS NULL
      AND order_id IS NULL)
    OR
    (event_type = 'search'
      AND product_id IS NULL
      AND search_term IS NOT NULL
      AND length(search_term) > 0
      AND results_count IS NOT NULL
      AND results_count >= 0
      AND order_id IS NULL)
    OR
    (event_type = 'checkout_completed'
      AND product_id IS NULL
      AND search_term IS NULL
      AND results_count IS NULL
      AND order_id IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS customer_events_created_at_idx
  ON public.customer_events (created_at DESC);
CREATE INDEX IF NOT EXISTS customer_events_type_created_at_idx
  ON public.customer_events (event_type, created_at DESC);
CREATE INDEX IF NOT EXISTS customer_events_product_type_idx
  ON public.customer_events (product_id, event_type)
  WHERE product_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS customer_events_search_term_idx
  ON public.customer_events (search_term)
  WHERE event_type = 'search';
CREATE UNIQUE INDEX IF NOT EXISTS customer_events_checkout_once_idx
  ON public.customer_events (user_id, order_id)
  WHERE event_type = 'checkout_completed';

ALTER TABLE public.customer_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.customer_events FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.customer_events TO authenticated;
REVOKE ALL ON SEQUENCE public.customer_events_id_seq FROM PUBLIC, anon;
GRANT USAGE, SELECT ON SEQUENCE public.customer_events_id_seq TO authenticated;

DROP POLICY IF EXISTS "Customers read own behavior events"
  ON public.customer_events;
CREATE POLICY "Customers read own behavior events"
  ON public.customer_events
  FOR SELECT
  TO authenticated
  USING (user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Admins read customer behavior events"
  ON public.customer_events;
CREATE POLICY "Admins read customer behavior events"
  ON public.customer_events
  FOR SELECT
  TO authenticated
  USING ((SELECT public.current_user_is_admin()));

DROP POLICY IF EXISTS "Event reads require owner or admin"
  ON public.customer_events;
CREATE POLICY "Event reads require owner or admin"
  ON public.customer_events
  AS RESTRICTIVE
  FOR SELECT
  TO authenticated
  USING (
    user_id = (SELECT auth.uid())
    OR (SELECT public.current_user_is_admin())
  );

DROP POLICY IF EXISTS "Customers insert non-purchase events"
  ON public.customer_events;
CREATE POLICY "Customers insert non-purchase events"
  ON public.customer_events
  FOR INSERT
  TO authenticated
  WITH CHECK (
    user_id = (SELECT auth.uid())
    AND event_type IN ('product_view', 'add_to_cart', 'search')
  );

DROP POLICY IF EXISTS "Event inserts are owner-scoped and non-purchase"
  ON public.customer_events;
CREATE POLICY "Event inserts are owner-scoped and non-purchase"
  ON public.customer_events
  AS RESTRICTIVE
  FOR INSERT
  TO authenticated
  WITH CHECK (
    user_id = (SELECT auth.uid())
    AND event_type IN ('product_view', 'add_to_cart', 'search')
  );

CREATE OR REPLACE FUNCTION public.set_customer_event_server_fields()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
  NEW.user_id := auth.uid();
  NEW.created_at := now();
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS customer_events_set_server_fields
  ON public.customer_events;
CREATE TRIGGER customer_events_set_server_fields
  BEFORE INSERT ON public.customer_events
  FOR EACH ROW
  EXECUTE FUNCTION public.set_customer_event_server_fields();

CREATE OR REPLACE FUNCTION public.record_checkout_completed_event(
  p_order_id text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_order_id IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.orders
    WHERE id::text = p_order_id
      AND user_id = auth.uid()
  ) THEN
    RAISE EXCEPTION 'No completed order found for this account';
  END IF;

  INSERT INTO public.customer_events (user_id, event_type, order_id)
  VALUES (auth.uid(), 'checkout_completed', p_order_id)
  ON CONFLICT (user_id, order_id)
    WHERE event_type = 'checkout_completed'
    DO NOTHING;
END;
$function$;

REVOKE ALL ON FUNCTION public.record_checkout_completed_event(text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_checkout_completed_event(text)
  TO authenticated;

COMMIT;
